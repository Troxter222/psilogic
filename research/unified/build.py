#!/usr/bin/env python3
"""Build one article: PsiLogic description, full convergence theory, benchmarks.

Inputs are read only. Numerical results and all theorem/proof environments are
preserved. Generated outputs live here and in output/pdf/paper_unified.pdf.
"""

from __future__ import annotations
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "output" / "pdf" / "paper_unified.pdf"
BUILD = HERE / "build"


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise ValueError(f"Expected one occurrence of {old[:90]!r}; found {text.count(old)}")
    return text.replace(old, new, 1)


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def compose():
    paths = [
        ROOT / "PAPER.md",
        ROOT / "arxiv/paper.tex",
        ROOT / "output/pdf/paper.pdf",
        ROOT / "research/convergence/manuscript.tex",
        ROOT / "research/convergence/manuscript.pdf",
        ROOT / "research/convergence/references.bib",
    ]
    baseline = {str(p.relative_to(ROOT)): sha(p) for p in paths}
    article = (ROOT / "arxiv/paper.tex").read_text()
    theory = (ROOT / "research/convergence/manuscript.tex").read_text()
    before_refs, refs_and_appendices = article.split(r"\section*{References}", 1)
    _, appendices = refs_and_appendices.split(
        r"\section*{Appendix A. Later per-seed primary outcomes}", 1
    )
    appendices = r"\section*{Appendix A. Later per-seed primary outcomes}" + appendices
    appendices = appendices.split(r"\end{document}", 1)[0]
    appendices = re.sub(r"\\clearpage\s*$", "", appendices).strip()

    preamble, main = before_refs.split(r"\begin{document}", 1)
    preamble = preamble.replace(
        "% Generated from PAPER.md. Edit the Markdown source.",
        "% Generated by research/unified/build.py from the empirical and theory sources.",
    )
    preamble = preamble.replace(
        r"\usepackage{amsmath,amssymb,graphicx,booktabs,tabularx,array}",
        r"\usepackage{amsmath,amssymb,amsthm,mathtools,graphicx,booktabs,longtable,tabularx,array}",
    )
    preamble = preamble.replace(
        r"\usepackage{xcolor,hyperref,fancyvrb,enumitem}",
        r"\usepackage{xcolor,microtype,hyperref,fancyvrb,enumitem}"
        + "\n"
        + r"\usepackage[numbers,sort&compress]{natbib}",
    )
    definitions = theory[theory.index(r"\newtheorem{theorem}") : theory.index(r"\title{")]
    preamble = replace_once(
        preamble,
        r"\title{PsiLogic: Chaos-Aware Active Cancellation for Adam with a Fair Cross-Domain Benchmark}",
        definitions
        + r"\title{PsiLogic: Chaos-Aware Active Cancellation for Adam\\"
        + r"\large Implementation, Convergence Theory, and Cross-Domain Benchmarks}",
    )
    preamble += (
        "\n"
        + r"\hypersetup{pdftitle={PsiLogic: Implementation, Convergence Theory, and Cross-Domain Benchmarks},pdfauthor={Ali Sultonov},pdfsubject={Unified empirical article and complete conditional convergence proofs}}"
        + "\n"
    )

    main = replace_once(
        main,
        "Local revision of the original preprint: implementation and empirical audit, revised 15 October 2026. Audited software version: 0.6.0.",
        "Unified local revision: implementation and empirical audit of 15 October 2026, with convergence theory and complete proofs integrated on 16 October 2026. Audited software version: 0.6.0.",
    )
    theory_abstract = r"""
The convergence analysis retains the full implemented detector, both Adam
moments, bias correction, and the actual epsilon convention. Under explicit
bounded-gradient and small-step assumptions, with parameter decay and gradient
preprocessing disabled, it proves a pathwise stationarity-energy bound and
$O(T^{-1})$ average squared gradient for deterministic gradients. Stochastic
conclusions require controlled oracle error. Counterexamples identify failures
of broader claims, and ten scalar and finite-sum lemmas are kernel-checked in
Lean 4. These guarantees do not certify the benchmark configurations or
establish an unconditional advantage over AdamW.
"""
    main = replace_once(main, r"\end{abstract}", theory_abstract + "\n" + r"\end{abstract}")
    main = replace_once(
        main,
        "We make no claim of priority over all gradient-dependent learning-rate methods and provide no convergence theorem.",
        r"We make no claim of priority over all gradient-dependent learning-rate methods. Section~\ref{sec:convergence} establishes conditional convergence guarantees for a precisely specified Adam configuration and states the modes and noise regimes they exclude.",
    )
    main = replace_once(
        main,
        r"\section{The implemented algorithm}",
        r"\section{The implemented algorithm}\label{sec:implemented}",
    )
    main = replace_once(
        main,
        r"\section{Evidence and protocol}",
        r"\section{Evidence and protocol}\label{sec:evidence}",
    )
    main = replace_once(
        main,
        "There is no later diffusion outcome, later step history, matched time-to-quality analysis, external replication established by these artifacts, or convergence proof.",
        r"There is no later diffusion outcome, later step history, matched time-to-quality analysis, or external replication established by these artifacts. The convergence theorem in Section~\ref{sec:convergence} applies under its stated restrictions; it does not certify the finite-precision benchmark configurations or explain their quality ordering.",
    )
    main = replace_once(
        main,
        "PAPER.md is the source for generated LaTeX and PDF. Tables, figures, paired tests, and file hashes are derived from saved measurements:",
        r"The empirical source is \path{PAPER.md}; the theoretical source is \path{research/convergence/manuscript.tex}. The combined article is assembled by \path{research/unified/build.py}. Tables, figures, paired tests, and file hashes are derived from saved measurements:",
    )
    main = replace_once(
        main,
        "python scripts/build_arxiv_pdf.py\n",
        "python scripts/build_arxiv_pdf.py\npython3 research/unified/build.py\n",
    )
    main = replace_once(
        main,
        r"Canonical output is \path{output/pdf/paper.pdf}, with copies at \path{arxiv/paper.pdf} and psilogic-arxiv.pdf.",
        r"The combined output is \path{output/pdf/paper_unified.pdf}, with editable LaTeX and a shared bibliography in \path{research/unified/}. The standalone empirical build still writes \path{output/pdf/paper.pdf} and its original copies.",
    )
    main = replace_once(
        main,
        "These findings justify controlled evaluation, not a universal quality claim or a claim that historical tables validate every detail of today's code.",
        r"These findings justify controlled evaluation, not a universal quality claim or a claim that historical tables validate every detail of today\textquotesingle s code. The full-detector Adam analysis proves deterministic stationarity and conditional stochastic bounds under explicit restrictions; the counterexamples and the conservative sufficient step bound delimit what those results establish. Ten checked Lean lemmas verify a scalar algebraic core, while the complete convergence theorem remains an informal mathematical proof.",
    )
    # textquotesingle is unnecessary with this font setup; use the source apostrophe.
    main = main.replace(r"today\textquotesingle s", "today's")
    main = main.replace(
        r"https://arxiv.org/pdf/2607.16268,}", r"https://arxiv.org/pdf/2607.16268},"
    )
    for old, key in {
        "[1]": "psilogic2026preprint",
        "[2]": "kingma2015adam",
        "[3]": "loshchilov2019decoupled",
        "[4]": "chen2023lion",
        "[5]": "psilogicsoftware",
    }.items():
        main = main.replace(old, r"\citep{" + key + "}")
    main = main.replace("../arxiv/figures/", "../../arxiv/figures/")

    theory_body = theory.split(r"\section{Introduction and contributions}", 1)[1]
    theory_body = theory_body.split(r"\bibliographystyle", 1)[0]
    theory_body = r"\subsection{Scope and mathematical contributions}" + theory_body
    # Demote original headings under the single convergence section.
    theory_body = re.sub(
        r"\\(section|subsection)\{",
        lambda m: "\\" + ("subsection" if m[1] == "section" else "subsubsection") + "{",
        theory_body,
    )
    # The scope heading inserted above must remain a subsection.
    theory_body = theory_body.replace(
        r"\subsubsection{Scope and mathematical contributions}",
        r"\subsection{Scope and mathematical contributions}",
        1,
    )
    theory_body = theory_body.replace(
        r"\subsection{Exact algorithm specification}",
        r"\subsection{Notation and recurrence for the proofs}",
    )
    theory_body = theory_body.replace(
        r"\subsection{Levels B--D: exact cancellation, moments, and bias correction}",
        r"\subsection{Exact cancellation, moments, and bias correction}",
    )
    theory_body = theory_body.replace(
        r"\subsection{Level A: a simplified stochastic baseline}",
        r"\subsection{A simplified stochastic baseline}",
    )
    intro = r"""
\section{Convergence Theory and Proofs}\label{sec:convergence}
This section supplies the complete conditional convergence analysis for the
update described in Section~\ref{sec:implemented}. It is placed before the
empirical protocol to make the mathematical guarantee and its limits explicit
before the benchmark results are interpreted. The deterministic guarantee,
stochastic error bounds, and counterexamples concern precisely stated
configurations; they do not validate every benchmark preset.

For the proofs, $x_t$ concatenates the parameter tensors $\theta_{i,t}$,
$u_t^{(b)}$ denotes the trust $T_{i,t}$, and $s_t$ denotes the soft signal
$C_{i,t}$ of the implementation section. The notation $h_t=\nabla f(x_t)$
means the true objective gradient here; the earlier implementation notation
$h_{i,t}$ meant the received raw gradient. This distinction is needed to state
oracle error. The recurrence below restates the same algorithm in this proof
notation, preserving its epsilon convention and update order. All sidecar
filenames and the \texttt{lean/} directory named in this section are relative
to \path{research/convergence/}.
\setlength{\parskip}{0pt}
\numberwithin{equation}{section}
"""
    # All mathematical theorem/proof environments must survive byte for byte.
    for env in [
        "theorem",
        "lemma",
        "proposition",
        "corollary",
        "assumption",
        "definition",
        "proof",
    ]:
        pattern = r"\\begin\{" + env + r"\}.*?\\end\{" + env + r"\}"
        old = re.findall(pattern, theory, flags=re.S)
        new = re.findall(pattern, theory_body, flags=re.S)
        if old != new:
            raise ValueError(f"Mathematical {env} blocks were altered")
    before, after = main.split(r"\section{Evidence and protocol}", 1)
    body = (
        before
        + intro
        + theory_body
        + "\n"
        + r"\clearpage"
        + "\n"
        + r"\setlength{\parskip}{4pt}"
        + "\n"
        + r"\section{Evidence and protocol}"
        + after
    )
    for letter, title in [
        ("A", "Later per-seed primary outcomes"),
        ("B", "Reference selected rates"),
        ("C", "Reference per-seed primary outcomes"),
    ]:
        appendices = appendices.replace(
            r"\section*{Appendix " + letter + ". " + title + "}",
            r"\section{" + title + r"}\label{app:empirical-" + letter.lower() + "}",
        )
    appendix = "\n" + r"\clearpage" + "\n" + r"\appendix" + "\n" + appendices
    result = (
        preamble
        + "\n"
        + r"\begin{document}"
        + body
        + appendix
        + "\n"
        + r"\clearpage"
        + "\n"
        + r"\bibliographystyle{unsrtnat}"
        + "\n"
        + r"\bibliography{references}"
        + "\n"
        + r"\end{document}"
        + "\n"
    )
    table_pattern = r"\\begin\{tabularx\}.*?\\end\{tabularx\}"
    if re.findall(table_pattern, article, re.S) != re.findall(table_pattern, result, re.S):
        raise ValueError("Empirical table contents were altered")
    original_figures = re.findall(r"\\includegraphics\[[^\]]*\]\{([^}]+)\}", article)
    unified_figures = re.findall(r"\\includegraphics\[[^\]]*\]\{([^}]+)\}", result)
    if [Path(p).name for p in original_figures] != [Path(p).name for p in unified_figures]:
        raise ValueError("Empirical figures were altered or reordered")
    bib = (
        (ROOT / "research/convergence/references.bib").read_text()
        + r"""
@misc{psilogic2026preprint,
 author={Sultonov, Ali},
 title={{PsiLogic}: Chaos-Aware Active Cancellation for {Adam} with a Fair Cross-Domain Benchmark},
 year={2026}, howpublished={arXiv:2607.16268v1 [cs.LG]},
 url={https://arxiv.org/pdf/2607.16268}, doi={10.48550/arXiv.2607.16268},
 note={Original preprint, 5 July 2026}
}
@misc{psilogicsoftware,
 author={Sultonov, Ali}, title={{PsiLogic} software and {FairBench} artifacts},
 howpublished={Zenodo supplementary software record},
 doi={10.5281/zenodo.18739857}, url={https://doi.org/10.5281/zenodo.18739857}
}
"""
    )
    (HERE / "paper.tex").write_text(result)
    (HERE / "references.bib").write_text(bib)
    record = {
        "source_sha256": baseline,
        "structure": "description and algorithm; full convergence proofs; protocol and benchmarks; discussion and conclusion; empirical appendices; unified bibliography",
        "mathematical_environment_blocks_preserved": {
            env: len(re.findall(r"\\begin\{" + env + r"\}", theory))
            for env in [
                "theorem",
                "lemma",
                "proposition",
                "corollary",
                "assumption",
                "definition",
                "proof",
            ]
        },
        "empirical_tables_preserved": len(re.findall(r"\\begin\{tabularx\}", article)),
        "empirical_figures_preserved": len(re.findall(r"\\includegraphics", article)),
        "empirical_table_blocks_byte_identical": True,
        "editorial_changes": [
            "One title, author block, and abstract; theory abstract integrated into main abstract",
            "Complete theory inserted after algorithm and before evidence/protocol",
            "Mathematical notation bridge added; all theorem and proof blocks preserved exactly",
            "Contradictory no-convergence-proof sentences updated with explicit theorem scope",
            "Shared BibTeX bibliography and linked citations; empirical appendices numbered automatically",
            "Build paths and reproduction instructions updated for unified output",
        ],
    }
    return baseline, record


def main():
    BUILD.mkdir(parents=True, exist_ok=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    baseline, record = compose()
    commands = [
        [
            "pdflatex",
            "-interaction=nonstopmode",
            "-halt-on-error",
            "-output-directory=build",
            "paper.tex",
        ],
        ["bibtex", "build/paper"],
        [
            "pdflatex",
            "-interaction=nonstopmode",
            "-halt-on-error",
            "-output-directory=build",
            "paper.tex",
        ],
        [
            "pdflatex",
            "-interaction=nonstopmode",
            "-halt-on-error",
            "-output-directory=build",
            "paper.tex",
        ],
    ]
    records = []
    for i, command in enumerate(commands, 1):
        run = subprocess.run(
            command, cwd=HERE, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT
        )
        (BUILD / f"pass_{i}.log").write_text(run.stdout)
        records.append(
            {"command": command, "exit_code": run.returncode, "log": f"build/pass_{i}.log"}
        )
        if run.returncode:
            print(run.stdout[-5000:])
            raise SystemExit(run.returncode)
    log = (BUILD / "paper.log").read_text()
    issues = [
        line
        for line in log.splitlines()
        if "Overfull" in line or "undefined" in line or "Rerun to get" in line
    ]
    changed = [name for name, h in baseline.items() if sha(ROOT / name) != h]
    if changed:
        raise RuntimeError(f"Input sources unexpectedly changed: {changed}")
    shutil.copy2(BUILD / "paper.pdf", OUT)
    record.update(
        {
            "commands": records,
            "status": "pass" if not issues else "needs_layout_review",
            "issues": issues,
            "input_sources_unchanged": True,
            "tex_sha256": sha(HERE / "paper.tex"),
            "pdf_sha256": sha(OUT),
            "output": str(OUT.relative_to(ROOT)),
        }
    )
    (HERE / "build_results.json").write_text(json.dumps(record, indent=2) + "\n")
    print(
        json.dumps(
            {
                k: record[k]
                for k in [
                    "status",
                    "issues",
                    "input_sources_unchanged",
                    "output",
                    "mathematical_environment_blocks_preserved",
                ]
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
